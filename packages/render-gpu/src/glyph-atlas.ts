/**
 * Zero-dependency, zero-Canvas-2D shelf-packed R8 bitmap glyph atlas for `@jiange/render-gpu`.
 *
 * Rasterizes a procedural 5x7 bitmap font (ASCII 0x20..0x7E + fallback glyph for non-ASCII/CJK)
 * directly into an R8 `Uint8Array` buffer suitable for WebGPU `r8unorm` and WebGL2 `R8` textures.
 */

export const GLYPH_CELL_WIDTH = 5;
export const GLYPH_CELL_HEIGHT = 7;
export const GLYPH_CELL_ADVANCE = 6;

export interface GlyphMetrics {
  u0: number;
  v0: number;
  u1: number;
  v1: number;
  width: number;
  height: number;
  advance: number;
}

export interface GlyphAtlasOptions {
  width?: number;
  height?: number;
  padding?: number;
}

const ASCII_START = 0x20;
const ASCII_END = 0x7e;
const FALLBACK_KEY = 0;

