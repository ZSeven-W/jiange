function resolveGlyphKey(char: string): number {
  const cp = char.codePointAt(0);
  if (cp !== undefined && cp >= ASCII_START && cp <= ASCII_END) {
    return cp;
  }
  return FALLBACK_KEY;
}

/** Shelf-packed single-channel (R8) procedural bitmap glyph atlas. */
export class GlyphAtlas {
  readonly width: number;
  readonly height: number;
  readonly padding: number;
  readonly data: Uint8Array;

  private cursorX: number;
  private cursorY: number;
  private shelfHeight = 0;
  private cache = new Map<number, GlyphMetrics>();
  private _dirty = false;
  private _version = 0;

  constructor(options: GlyphAtlasOptions = {}) {
    this.width = Math.max(16, Math.floor(options.width ?? 256));
    this.height = Math.max(16, Math.floor(options.height ?? 256));
    this.padding = Math.max(0, Math.floor(options.padding ?? 1));
    this.data = new Uint8Array(this.width * this.height);
    this.cursorX = this.padding;
    this.cursorY = this.padding;
  }

  get dirty(): boolean {
    return this._dirty;
  }

  get version(): number {
    return this._version;
  }

  get glyphCount(): number {
    return this.cache.size;
  }

  hasGlyph(char: string): boolean {
    return this.cache.has(resolveGlyphKey(char));
  }

  markClean(): void {
    this._dirty = false;
  }

  clear(): void {
    this.data.fill(0);
    this.cache.clear();
    this.cursorX = this.padding;
    this.cursorY = this.padding;
    this.shelfHeight = 0;
    this._dirty = true;
    this._version++;
  }

  /** Retrieve or shelf-pack and rasterize a glyph into the R8 atlas buffer. */
  getGlyph(char: string): GlyphMetrics {
    const key = resolveGlyphKey(char);
    const cached = this.cache.get(key);
    if (cached) return cached;

    const glyphW = GLYPH_CELL_WIDTH;
    const glyphH = GLYPH_CELL_HEIGHT;

    if (this.cursorX + glyphW + this.padding > this.width) {
      this.cursorX = this.padding;
      this.cursorY += this.shelfHeight + this.padding;
      this.shelfHeight = 0;
    }
    if (this.cursorY + glyphH + this.padding > this.height) {
      this.clear();
    }

    const gx = this.cursorX;
    const gy = this.cursorY;
    const bitmap = key === FALLBACK_KEY ? FALLBACK_BITMAP : FONT_5X7[key - ASCII_START];

    for (let row = 0; row < glyphH; row++) {
      const bits = bitmap[row];
      const rowOffset = (gy + row) * this.width + gx;
      for (let col = 0; col < glyphW; col++) {
        if ((bits >> (glyphW - 1 - col)) & 1) {
          this.data[rowOffset + col] = 255;
        }
      }
    }

    const metrics: GlyphMetrics = {
      u0: gx / this.width,
      v0: gy / this.height,
      u1: (gx + glyphW) / this.width,
      v1: (gy + glyphH) / this.height,
      width: glyphW,
      height: glyphH,
      advance: GLYPH_CELL_ADVANCE,
    };

    this.cursorX += glyphW + this.padding;
    this.shelfHeight = Math.max(this.shelfHeight, glyphH);
    this.cache.set(key, metrics);
    this._dirty = true;
    this._version++;
    return metrics;
  }
}
