import { Doc, encodeClientMsg, encodeOps, eqId, idKey, type Op, type OpId, Tx, UndoManager } from "@zseven-w/collab";
import { TITLE } from "./model";
import { planFindBatch, writeFindBatchTables } from "./find-batch";
import { replaceMatches, resolveFindMatch, type FindMatch } from "./find-replace";
import { FIND_CHANGED_CODEPOINT_LIMIT, FIND_FRAME_LIMIT, FIND_REPLACEMENT_BYTES_LIMIT, FIND_WORK_LIMIT } from "./find-replace-safety";
import { tableHistoryGuard } from "./table-history-undo";

const STATE_LIMIT = 16 << 20;
export type AtomicFindStatus = "ready" | "unchanged" | "stale" | "invalid_title" | "invalid_text" | "unsupported_title" | "size" | "work" | "unavailable" | "preflight";
export type AtomicTableChange = { block: OpId; before: string[][]; after: string[][]; cells: { row: number; col: number }[]; beforeData: string | null; afterData: string | null; guard: string };
/** The plan is bound to the original replica and an exclusively owned author.
 * It is a preview only: no operation is applied to the original document. */
export type AtomicFindPlan = Readonly<{ doc: Doc; author: number; ops: readonly Op[]; text: Tx; textBlocks: readonly { block: OpId; parent: OpId }[]; tables: readonly AtomicTableChange[]; titleBefore: string; titleAfter: string; count: number }>;
export type AtomicFindPreparation = { status: "ready"; plan: AtomicFindPlan } | { status: Exclude<AtomicFindStatus, "ready"> };
const states = new WeakMap<AtomicFindPlan, { base: Uint8Array; post: Uint8Array }>();
function freezeTree(value: unknown): void {
  if (!value || typeof value !== "object" || Object.isFrozen(value) || ArrayBuffer.isView(value)) return;
  for (const child of Object.values(value)) freezeTree(child);
  Object.freeze(value);
}
function clonePlain<T>(value: T): T { return typeof structuredClone === "function" ? structuredClone(value) : JSON.parse(JSON.stringify(value)) as T; }
export function atomicFindPostState(plan: AtomicFindPlan): Uint8Array | null { return states.get(plan)?.post.slice() ?? null; }

function validUnicode(text: string): boolean {
  for (let i = 0; i < text.length; i++) {
    const n = text.charCodeAt(i);
    if (n >= 0xd800 && n <= 0xdbff) { const next = text.charCodeAt(++i); if (!(next >= 0xdc00 && next <= 0xdfff)) return false; }
    else if (n >= 0xdc00 && n <= 0xdfff) return false;
  }
  return true;
}
export function validAtomicTitle(title: string): boolean { return validUnicode(title) && title === title.trim() && [...title].length <= 200 && !/[\r\n]/.test(title); }
function withinFrame(ops: Op[]): boolean { return !ops.length || encodeClientMsg({ type: "ops", batch: encodeOps(ops) }).byteLength <= FIND_FRAME_LIMIT; }

/** Build and size-check a title/body/table replacement against an isolated
 * replica. The caller must own `author` exclusively until the resulting batch
 * is confirmed or definitively rejected by the server. */
export function prepareAtomicFindBatch(doc: Doc, author: number, matches: readonly FindMatch[], replacement: string, directoryTitle: string): AtomicFindPreparation {
  if (!Number.isSafeInteger(author) || author <= 0 || author === doc.client || !matches.length || !matches.some((match) => eqId(match.block, TITLE)) || matches.some((match) => match.doc !== doc || match.mention)) return { status: "unavailable" };
  if (!validUnicode(replacement) || matches.some((match) => !validUnicode(match.text))) return { status: "invalid_text" };
  if (replacement.length > FIND_REPLACEMENT_BYTES_LIMIT || replacement.length * matches.length > FIND_REPLACEMENT_BYTES_LIMIT || new TextEncoder().encode(replacement).length * matches.length > FIND_REPLACEMENT_BYTES_LIMIT) return { status: "size" };
  if ([...replacement].length * matches.length + matches.reduce((sum, match) => sum + (match.table ? match.end - match.start : match.ids.length), 0) > FIND_CHANGED_CODEPOINT_LIMIT) return { status: "size" };
  try {
    if (!doc.hasBlock(TITLE) || doc.blockInfo(TITLE).type !== "title" || doc.text(TITLE) !== directoryTitle) return { status: "stale" };
    const baseState = doc.encodeState(); if (baseState.byteLength > STATE_LIMIT) return { status: "work" };
    const copy = Doc.fromState(author, baseState), rebound = matches.map((match) => ({ ...match, doc: copy }));
    const plan = planFindBatch(copy, rebound, replacement); if (!plan) return { status: "stale" };
    let work = plan.tables.reduce((sum, table) => sum + table.before.reduce((n, row) => n + row.length + row.reduce((total, cell) => total + cell.length, 0), 0), 0);
    for (const match of plan.text) { work += copy.visibleIds(match.block).length; if (work > FIND_WORK_LIMIT) return { status: "work" }; }
    if (work > FIND_WORK_LIMIT) return { status: "work" };
    // The title control is plain text and the conditional API rejects title
    // mark operations, including marks generated by a later inverse.
    for (const match of plan.text.filter((item) => eqId(item.block, TITLE))) {
      const current = resolveFindMatch(copy, match); if (!current) return { status: "stale" };
      if (copy.richChars(TITLE).slice(current.start, current.end).some((char) => Object.keys(char.marks).length)) return { status: "unsupported_title" };
    }
    const titleBefore = copy.text(TITLE), text = new Tx(copy), replaced = replaceMatches(text, plan.text, replacement, { allowTitle: true });
    if (replaced.skipped || replaced.replaced !== plan.text.length) return { status: "stale" };
    const titleAfter = copy.text(TITLE); if (!validAtomicTitle(titleAfter)) return { status: "invalid_title" };
    const beforeData = new Map(plan.tables.map((table) => { const version = copy.propVersion(table.block, "tableData"); return [idKey(table.block), version ? idKey(version) : null]; }));
    const tableOps = writeFindBatchTables(copy, plan.tables.map((table) => ({ block: table.block, rows: table.after })));
    const ops = [...text.ops, ...tableOps]; if (!withinFrame(ops)) return { status: "size" };
    if (!ops.length) return { status: "unchanged" };
    const postState = copy.encodeState(); if (postState.byteLength > STATE_LIMIT) return { status: "work" };
    // Ensure both the forward action and its first inverse fit the wire limit.
    const inverseDoc = Doc.fromState(author, postState), undo = new UndoManager(); undo.record(text, null, null);
    const inverseText = undo.undo(inverseDoc)?.ops ?? [];
    const inverseTables = writeFindBatchTables(inverseDoc, plan.tables.map((table) => ({ block: table.block, rows: table.before })));
    if (!withinFrame([...inverseText, ...inverseTables])) return { status: "size" };
    const blocks = new Map<string, { block: OpId; parent: OpId }>();
    for (const match of plan.text) blocks.set(`${match.block.client}:${match.block.clock}`, { block: match.block, parent: match.parent });
    const safeOps = clonePlain(ops), textBlocks = clonePlain([...blocks.values()]), tables = clonePlain(plan.tables.map(({ block, before, after, cells }) => { const version = copy.propVersion(block, "tableData"); return { block, before, after, cells, beforeData: beforeData.get(idKey(block)) ?? null, afterData: version ? idKey(version) : null, guard: tableHistoryGuard(copy, block) }; }));
    text.items = clonePlain(text.items); text.ops = safeOps.slice(0, text.ops.length);
    freezeTree(safeOps); freezeTree(text.ops); freezeTree(text.items); freezeTree(textBlocks); freezeTree(tables); Object.freeze(text);
    const result: AtomicFindPlan = Object.freeze({ doc, author, ops: safeOps, text, textBlocks, titleBefore, titleAfter, count: matches.length, tables });
    states.set(result, { base: baseState, post: postState });
    return { status: "ready", plan: result };
  } catch { return { status: "preflight" }; }
}

/** A pending plan may only be sent from the exact state it was prepared on. */
export function atomicFindPlanIsCurrent(plan: AtomicFindPlan, doc: Doc): boolean {
  if (doc !== plan.doc) return false;
  try { const base = states.get(plan)?.base; if (!base) return false; const now = doc.encodeState(); return now.byteLength === base.byteLength && now.every((value, index) => value === base[index]); }
  catch { return false; }
}
